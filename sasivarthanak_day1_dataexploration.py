import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

data = {
    "Hours_Studied": [2, 5, 3, 7, 1, 6, 4, 8, 5, 3],
    "Attendance": [60, 90, 75, 95, 50, 88, 80, 98, 85, 70],
    "Previous_Score": [45, 70, 55, 82, 40, 78, 65, 90, 72, 58],
    "Final_Score": [42, 76, 58, 88, 35, 82, 68, 94, 79, 60]
}
df = pd.DataFrame(data)
print(df.head(10))
print("Shape:", df.shape)
print(df.isnull().sum())

sns.barplot(data=df, x="Hours_Studied", y="Final_Score")
plt.title("Study Hours vs Final Score")
plt.show()